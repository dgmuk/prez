for p in paths:
    t = p.read_text(encoding="utf-8")
    orig = t
    for a, b in phrase_map:
        t = t.replace(a, b)
    # digit–digit -> digit-digit
    t = re.sub(r"(?<=\d)–(?=\d)", "-", t)
    t = re.sub(r"(?<=\d)—(?=\d)", "-", t)
    # spaced em/en dash speech construction
    t = t.replace(" — ", ". ")
    t = t.replace(" – ", ", ")
    if t != orig:
        p.write_text(t, encoding="utf-8")
        print("updated", p.relative_to(ROOT))
    else:
        print("no change", p.relative_to(ROOT))

print("\n--- remaining em dashes (non-placeholder) ---")
for p in paths:
    for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
        if "—" not in line:
            continue
        # ignore pure placeholder patterns
        stripped = line
        for pat in ["'—'", '"—"', "`—`", "?? '—'", "|| '—'", ": '—'", "? '—'", "?? \"—\""]:
            stripped = stripped.replace(pat, "")
        # also ?? '—' and score === '—'
        stripped = re.sub(r"['\"]—['\"]", "", stripped)
        if "—" in stripped:
            print(f"{p.name}:{i}: {line.strip()[:140]}")
